#!/usr/bin/env python3
"""Unattended slice loop. Haiku 4.5 executes; this driver judges, commits, pushes.

Usage:  .venv/Scripts/python ops/haiku-runner/driver.py            (run / resume)
        .venv/Scripts/python ops/haiku-runner/driver.py --dry-run  (print the plan)
        .venv/Scripts/python ops/haiku-runner/driver.py --only P01a
Restart is always safe: state lives in ops/haiku-runner/state.json.
"""
